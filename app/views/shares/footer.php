function openChat() {
  // Ẩn các nút
  document.querySelector('.btn-chat').style.display = 'none';
  document.querySelector('.note').style.display = 'none';
  const noShowBtn = document.querySelector('.no-show-btn');
  if (noShowBtn) noShowBtn.style.display = 'none';
  

  // ✅ Hiện khung chat & input
  document.getElementById("chat-content").classList.remove("chat-hidden");
  document.getElementById("chat-input-wrapper").classList.remove("chat-hidden");

  // Focus input
  document.getElementById("chat-input").focus();
  restoreChat();

}

function toggleChatbox() {
  const chat = document.getElementById("ai-chat-popup");
  chat.style.display = (chat.style.display === "block") ? "none" : "block";
}
function disableAutoChat() {
  localStorage.setItem('chatbox_disabled', 'true');
  hideChatbox();
}
window.addEventListener("DOMContentLoaded", function () {
  const disabled = localStorage.getItem('chatbox_disabled');
  const shown = localStorage.getItem('chatbox_shown');

  if (!disabled && !shown) {
    setTimeout(() => {
      document.getElementById("ai-chat-popup").style.display = "block";
      localStorage.setItem('chatbox_shown', 'true');
    }, 5000);
  }
});
